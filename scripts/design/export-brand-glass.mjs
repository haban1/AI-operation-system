import sharp from 'sharp';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {mkdir,writeFile} from 'node:fs/promises';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const base=path.join(root,'.codex-work/brand-glass-system-render');
const out=path.join(root,'public/branding');
await mkdir(out,{recursive:true});
const input=path.join(base,'brand-render.png');
const production=path.join(out,'intellidriven-ocean-glass.png');
const {data,info}=await sharp(input).ensureAlpha().raw().toBuffer({resolveWithObject:true});
const maskImage=sharp(path.join(base,'object-mask-0001.png'));
const maskMetadata=await maskImage.metadata();
if(maskMetadata.width!==info.width||maskMetadata.height!==info.height)throw new Error('Logo 与阴影遮罩尺寸不一致，请重新完成正式渲染。');
const mask=await maskImage.removeAlpha().greyscale().blur(0.6).raw().toBuffer();
for(let p=0;p<info.width*info.height;p++)data[p*4+3]=Math.round(data[p*4+3]*(0.15+0.85*mask[p]/255));
const refined=await sharp(data,{raw:info}).trim({threshold:12}).png().toBuffer();
await sharp(refined).resize({width:768}).png({compressionLevel:9}).toFile(production);
const metadata=await sharp(production).metadata();
await sharp(production).flatten({background:'#f5f9ff'}).resize({width:960}).png().toFile(path.join(base,'logo-on-light.png'));
await sharp(production).flatten({background:'#10191f'}).resize({width:960}).png().toFile(path.join(base,'logo-on-dark.png'));
await writeFile(path.join(base,'asset.json'),JSON.stringify({width:metadata.width,height:metadata.height,bytes:(await sharp(production).toBuffer()).length,alpha:metadata.hasAlpha},null,2));
console.log({width:metadata.width,height:metadata.height,alpha:metadata.hasAlpha});
