import { test } from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import { mkdtemp, writeFile, mkdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { createVideoStudio } from '../server.mjs';

test('bundled video ranges, mappings, category persistence, and traversal boundaries', async t => {
  const root=await mkdtemp(path.join(tmpdir(),'video-studio-test-'));
  await mkdir(path.join(root,'bundled','videos'),{recursive:true});
  await mkdir(path.join(root,'dist'));
  await writeFile(path.join(root,'bundled','videos','demo.mp4'),'0123456789');
  await writeFile(path.join(root,'bundled','manifest.json'),JSON.stringify({videos:[]}));
  await writeFile(path.join(root,'dist','index.html'),'<title>Studio</title>');
  const source=path.join(root,'source');await mkdir(source);await writeFile(path.join(source,'photo.jpg'),'image');
  const stateDir=path.join(root,'private'),studio=createVideoStudio({root,stateDir});
  const server=http.createServer((req,res)=>studio.handle(req,res,{mountPath:'/video-workbench'}));
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  t.after(async()=>{await new Promise(r=>server.close(r));await rm(root,{recursive:true,force:true});});
  const base=`http://127.0.0.1:${server.address().port}/video-workbench`;
  let response=await fetch(base+'/bundled/videos/demo.mp4',{headers:{Range:'bytes=3-6'}});
  assert.equal(response.status,206);assert.equal(response.headers.get('content-range'),'bytes 3-6/10');assert.equal(await response.text(),'3456');
  response=await fetch(base+'/bundled/videos/demo.mp4',{headers:{Range:'bytes=40-'}});assert.equal(response.status,416);
  response=await fetch(base+'/api/collections',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({path:source,name:'Material',kind:'content'})});
  assert.equal(response.status,201);const collection=await response.json();
  response=await fetch(base+'/api/media?collectionId='+collection.id);const listing=await response.json();
  assert.equal(listing.entries.length,1);assert.match(listing.entries[0].url,/^\/video-workbench\/api\/media\/file/);
  response=await fetch(base+'/api/assets/category',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({collectionId:collection.id,relativePath:'photo.jpg',category:'实操教学'})});assert.equal(response.status,200);
  const again=createVideoStudio({root,stateDir});assert.equal((await again.collections()).some(c=>c.id===collection.id),true);
  response=await fetch(base+'/api/media/file?collectionId='+collection.id+'&path=..%2Fbundled%2Fmanifest.json');assert.equal(response.status,403);
  response=await fetch(base+'/api/collections',{method:'POST',headers:{Origin:'https://unrelated.example','Content-Type':'application/json'},body:JSON.stringify({path:source})});assert.equal(response.status,403);
  response=await fetch(base+'/api/collections/'+collection.id,{method:'DELETE'});assert.equal(response.status,200);
  response=await fetch(base+'/api/media?collectionId='+collection.id);assert.equal(response.status,404);
});
