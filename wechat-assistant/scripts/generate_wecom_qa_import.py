def copy_row_style(ws, source_row: int, target_row: int, max_col: int) -> None:
    for col in range(1, max_col + 1):
        source = ws.cell(source_row, col)
        target = ws.cell(target_row, col)
        if source.has_style:
            target._style = copy(source._style)
        if source.number_format:
            target.number_format = source.number_format
        if source.alignment:
            target.alignment = copy(source.alignment)


def main() -> None:
    wb = openpyxl.load_workbook(TEMPLATE)
    ws = wb["快捷回复列表"]

    for row_idx in range(8, ws.max_row + 1):
        for col_idx in range(1, 5):
            ws.cell(row_idx, col_idx).value = None

    for offset, row in enumerate(QA_ROWS, start=8):
        copy_row_style(ws, 8, offset, 4)
        for col_idx, value in enumerate(row, start=1):
            cell = ws.cell(offset, col_idx)
            cell.value = value
            cell.alignment = openpyxl.styles.Alignment(wrap_text=True, vertical="top")

    widths = {"A": 14, "B": 24, "C": 34, "D": 68}
    for col, width in widths.items():
        ws.column_dimensions[col].width = width

    for row_idx in range(8, 8 + len(QA_ROWS)):
        ws.row_dimensions[row_idx].height = 72

    ws.freeze_panes = "A8"
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    wb.save(OUTPUT)
    print(OUTPUT)


if __name__ == "__main__":
    main()
