import test from 'node:test';
import { revealControl } from './helpers/ui-details.js';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright-core';
import { startServer, jsonRequest, stopChild, cleanupDir, root ,openWorkspacePage} from './helpers/runtime.js';
const chrome = process.env.TEST_BROWSER_EXECUTABLE || ['C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', '/usr/bin/chromium', '/usr/bin/google-chrome'].find(p => fs.existsSync(p));
const preload = new URL('./helpers/ai-provider-fetch.js', import.meta.url).href;
test('AI settings browser: get models, select/manual edit, save, test, stale response and fallback', { skip: !chrome, timeout: 60000 }, async t => {
  const server = await startServer({ env: { NODE_ENV: 'test', NODE_OPTIONS: '--import=' + preload, SETTINGS_ENCRYPTION_KEY: 'ui-test-encryption-only', QWEN_API_KEY: '', DASHSCOPE_API_KEY: '' } });
  let browser;
  t.after(async () => { await browser?.close(); await stopChild(server.child); cleanupDir(server.dir); });
  browser = await chromium.launch({ executablePath: chrome, headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(server.base);
  await openWorkspacePage(page,'wecom');
  await page.locator('#aiSettingsDrawer').waitFor({ state: 'visible' });
  const form = page.locator('#aiSettingsForm');
  await form.locator('[name="mode"]').selectOption('online');
  await form.locator('[name="baseUrl"]').fill('https://provider.example/v1');
  await form.locator('[name="apiKey"]').fill('sk-fake-model-test-12345');
  for (const name of ['asrModel','contentModel','imageContentModel','trafficPredictionModel','embeddingModel']) assert.equal(await form.locator('[name="'+name+'"]').count(), 1, name+' remains configurable');
  await revealControl(form.locator('[name="contentModel"]'));
  await form.locator('[name="contentModel"]').fill('special-copy-model');
  const oldModel = await form.locator('[name="model"]').inputValue();
  await form.locator('#aiFetchModels').click();
  await page.waitForFunction(() => document.querySelector('[data-ai-model-picker="model"]').options.length === 3);
  assert.equal(await form.locator('[name="model"]').inputValue(), oldModel, 'fetch does not silently choose a model');
  await form.locator('[data-ai-model-picker="model"]').selectOption('chat-alpha');
  await revealControl(form.locator('[data-ai-model-picker="visionModel"]'));
  await form.locator('[data-ai-model-picker="visionModel"]').selectOption('vision-beta');
  assert.equal(await form.locator('[name="model"]').inputValue(), 'chat-alpha');
  assert.equal(await form.locator('#aiConnectionTest').isDisabled(), true);
  assert.match(await form.locator('#aiConnectionTestNote').innerText(), /先保存/);
  assert.equal((await jsonRequest(server.base, '/api/settings/ai')).data.settings.mode, 'mock');
  await form.locator('button[type="submit"]').click();
  await page.waitForFunction(() => document.querySelector('#aiSettingsForm [name="apiKey"]').value === '');
  assert.match(await page.locator('#aiSettingsDrawer .settings-status-card').innerText(), /已配置，待测试/);
  const saved = (await jsonRequest(server.base, '/api/settings/ai')).data.settings;
  assert.equal(saved.modelOverrides.contentModel, 'special-copy-model');
  await revealControl(form.locator('[name="contentModel"]'));
  await form.locator('[name="contentModel"]').fill('unsaved-copy-model');
  assert.equal(await form.locator('#aiConnectionTest').isDisabled(), true, 'dedicated model edits must also be saved before testing');
  await form.locator('[name="contentModel"]').fill('special-copy-model');
  await form.locator('#aiConnectionTest').click();
  await page.waitForFunction(() => document.querySelector('#aiSettingsDrawer .settings-status-card').textContent.includes('最近测试通过'));
  assert.match(await page.locator('#aiSettingsDrawer .settings-status-card').innerText(), /未验证视觉/);
  assert.match(await page.locator('#qwenMode').textContent(), /^AI：/);
  // A later manual model edit survives both list success and failure.
  await form.locator('[name="model"]').fill('custom-manual-model');
  await form.locator('#aiFetchModels').click();
  await page.waitForFunction(() => document.querySelector('[data-ai-model-picker="model"]').options.length === 3);
  assert.equal(await form.locator('[name="model"]').inputValue(), 'custom-manual-model');
  await form.locator('[name="baseUrl"]').fill('https://provider.example/unsupported/v1');
  await form.locator('#aiFetchModels').click();
  await page.waitForFunction(() => document.querySelector('#aiModelDiscoveryStatus').textContent.includes('不支持'));
  assert.equal(await form.locator('[data-ai-model-picker="model"]').isDisabled(), true);
  assert.equal(await form.locator('[name="model"]').inputValue(), 'custom-manual-model');
  // An old local backend has no models route: show restart instructions, not a provider error.
  await page.route('**/api/settings/ai/models', route => route.fulfill({ status: 404, json: { ok: false, message: '接口不存在' } }));
  await form.locator('#aiFetchModels').click();
  await page.waitForFunction(() => document.querySelector('#aiModelDiscoveryStatus').textContent.includes('重新启动本地服务'));
  assert.match(await form.locator('#aiModelDiscoveryStatus').innerText(), /不是千问返回的模型错误/);
  assert.equal(await form.locator('[name="model"]').inputValue(), 'custom-manual-model');
  await page.unroute('**/api/settings/ai/models');
  // Delayed results for old credentials cannot populate the new draft.
  let release;
  let requested;
  const gate = new Promise(resolve => { release = resolve; });
  const arrived = new Promise(resolve => { requested = resolve; });
  await page.route('**/api/settings/ai/models', async route => {
    requested(); await gate;
    await route.fulfill({ json: { models: ['stale-model'], message: 'stale response' } });
  });
  await form.locator('[name="baseUrl"]').fill('https://provider.example/v1');
  await form.locator('#aiFetchModels').click();
  await arrived;
  await form.locator('[name="apiKey"]').fill('new-draft-test-key');
  const staleResponse = page.waitForResponse('**/api/settings/ai/models');
  release();
  await staleResponse;
  await page.waitForTimeout(100);
  assert.equal(await form.locator('[data-ai-model-picker="model"]').isDisabled(), true);
  assert.equal(await form.locator('[data-ai-model-picker="model"] option').count(), 1);
  assert.match(await form.locator('#aiModelDiscoveryStatus').innerText(), /重新获取/);
  await page.unroute('**/api/settings/ai/models');
  // Restore the saved draft without writing anything to production state.
  await form.locator('[name="apiKey"]').fill('');
  await form.locator('[name="model"]').fill('chat-alpha');
  await form.locator('#aiFetchModels').click();
  await page.waitForFunction(() => document.querySelector('[data-ai-model-picker="model"]').options.length === 3);
  const output = path.join(root, 'outputs', 'ai-model-settings-20260921.png');
  fs.mkdirSync(path.dirname(output), { recursive: true });
  await page.locator('#aiSettingsDrawer').screenshot({ path: output });
  assert.deepEqual(errors, []);
});
