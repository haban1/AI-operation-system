import test from 'node:test';
import assert from 'node:assert/strict';
import { startServer, jsonRequest, stopChild, cleanupDir } from './helpers/runtime.js';
const preload = new URL('./helpers/ai-provider-fetch.js', import.meta.url).href;
const env = { NODE_ENV: 'test', NODE_OPTIONS: '--import=' + preload, SETTINGS_ENCRYPTION_KEY: 'ai-model-test-encryption-only', QWEN_API_KEY: '', DASHSCOPE_API_KEY: '' };
const config = { mode: 'online', baseUrl: 'https://provider.example/v1', apiKey: 'sk-fake-model-test-12345', model: 'chat-alpha', visionModel: 'vision-beta' };
test('models route uses draft credentials without saving and connection state follows save/test/clear', async t => {
  const server = await startServer({ env });
  t.after(async () => { await stopChild(server.child); cleanupDir(server.dir); });
  const request = (path, body) => jsonRequest(server.base, '/api/settings/ai' + path, body === undefined ? {} : { method: 'POST', body });
  const initial = (await request('')).data.settings;
  const discovered = await request('/models', config);
  assert.equal(discovered.response.status, 200);
  assert.deepEqual(discovered.data.models, ['chat-alpha', 'vision-beta']);
  assert.deepEqual((await request('')).data.settings, initial, 'discovery must not save draft fields');
  assert.equal(discovered.text.includes(config.apiKey), false);
  const saved = await request('', config);
  assert.equal(saved.data.settings.connectionTest.status, 'UNTESTED');
  const inherited = await request('/models', { baseUrl: config.baseUrl, apiKey: '' });
  assert.equal(inherited.response.status, 200);
  const changedHost = await request('/models', { baseUrl: 'https://other.example/v1' });
  assert.equal(changedHost.response.status, 400);
  assert.match(changedHost.data.message, /重新输入/);
  const unsafeSave = await request('', { baseUrl: 'https://other.example/v1' });
  assert.equal(unsafeSave.response.status, 400);
  const unsupported = await request('/models', { baseUrl: 'https://provider.example/unsupported/v1' });
  assert.equal(unsupported.response.status, 502);
  assert.match(unsupported.data.message, /手动/);
  const tested = await request('/test', {});
  assert.equal(tested.response.status, 200);
  assert.match(tested.data.result.message, /OCR.*未验证/);
  let settings = (await request('')).data.settings;
  assert.equal(settings.connectionTest.status, 'PASSED');
  assert.ok(settings.connectionTest.testedAt);
  assert.equal(JSON.stringify(settings).includes(config.apiKey), false);
  await request('', { model: 'denied-model' });
  assert.equal((await request('')).data.settings.connectionTest.status, 'UNTESTED');
  assert.equal((await request('/test', {})).response.status, 502);
  assert.equal((await request('')).data.settings.connectionTest.status, 'FAILED');
  await request('', { model: 'invalid-response' });
  assert.equal((await request('/test', {})).response.status, 502, 'HTTP 200 without a completion must not pass');
  await request('/clear-key', {});
  assert.equal((await request('')).data.settings.connectionTest.status, 'UNCONFIGURED');
});
